export type SourceStatus =
  | 'permanent'
  | 'permanentUnverified'
  | 'orb'
  | 'event'
  | 'paid'
  | 'endgame'
  | 'unavailable'
  | 'unknown';

export interface CharacterSource {
  /** In-game name. */
  name: string;
  /** Teams (mode) the research lists it for. */
  teams: string;
  status: SourceStatus;
  /** Where its shards come from. */
  source: string;
  /** When it is expected next, or a note. */
  next?: string;
  /** OFF = official post, 3P = fan site, szac. = estimate. */
  confidence: string;
  url?: string;
  /** End of a time-limited status (ISO date, usually estimated); after it `afterUntil` applies. */
  until?: string;
  afterUntil?: SourceStatus;
}

